import Foundation

/// One team waiting in a tunnel: a colour family and how many tiles it must carry home.
struct TeamSpec: Hashable, Codable {
    let family: Int
    let quota: Int
    init(_ family: Int, _ quota: Int) {
        self.family = family
        self.quota = quota
    }
}

/// Colour families of a level: each family has four glaze tones (light -> deep).
/// Built-in mosaics share GeneratedPalette.builtIn; photo mosaics derive theirs from the photo.
struct LevelPalette: Codable, Equatable {
    let names: [String]
    let tones: [[UInt32]]

    var familyCount: Int { tones.count }

    func tone(_ family: Int, _ tone: Int) -> UInt32 {
        guard family >= 0, family < tones.count else { return 0x888888 }
        let t = tones[family]
        return t[max(0, min(t.count - 1, tone))]
    }

    func name(_ family: Int) -> String {
        family >= 0 && family < names.count ? names[family] : "Colour \(family + 1)"
    }

    /// Relative luminance (0...1) of a family's main swatch, used to pick legible number ink.
    func luminance(_ family: Int) -> Double {
        let c = tone(family, 1)
        func lin(_ v: UInt32) -> Double {
            let s = Double(v) / 255
            return s <= 0.04045 ? s / 12.92 : pow((s + 0.055) / 1.055, 2.4)
        }
        return 0.2126 * lin((c >> 16) & 0xFF) + 0.7152 * lin((c >> 8) & 0xFF) + 0.0722 * lin(c & 0xFF)
    }
}

/// Everything that defines a level. Built-in levels are generated by Tools/generate_levels.py
/// (LevelData.swift); photo levels are built on the device by PhotoLevelBuilder.
struct LevelDefinition {
    let id: String
    let title: String
    let subtitle: String
    /// Mosaic rows; each character encodes family * 4 + tone as "a"..."x", "." = empty ground.
    let art: [String]
    let palette: LevelPalette
    let tunnels: [[TeamSpec]]
    let chambersGentle: Int
    let chambersClassic: Int
    let chambersExpert: Int
    /// The designer's winning order of tunnel taps (used by hints and the self-test).
    let solution: [Int]
    let goldenClaimsPerMove: [Int]
    let goldenClaimsHash: UInt64
    let goldenFinalStateHash: UInt64
    var isPhoto: Bool = false
    /// Share of careless games (random taps, no undo or assists) won on Gentle, Classic, Expert,
    /// measured by the level generator. Empty for pattern and photo levels (measured on the iPad).
    var carelessWins: [Double] = []
    /// Whether a sensible one-step player (always sends a team that can finish now, the one that
    /// claims most) wins on Gentle, Classic, Expert.
    var greedyWins: [Bool] = []
    /// Part of the Challenge or Master pack.
    var isChallenge: Bool = false
    /// Which pack the mosaic belongs to (a LevelCatalog.packs id such as "garden", "gallery" or
    /// "master"); "main" for the main mosaics and for pattern and photo levels.
    var pack: String = "main"

    /// Difficulty measurements shipped with the level, if any.
    var shippedStats: DifficultyStats? {
        guard carelessWins.count == 3, greedyWins.count == 3 else { return nil }
        return DifficultyStats(careless: carelessWins, greedy: greedyWins)
    }

    func chambers(for difficulty: Difficulty) -> Int {
        switch difficulty {
        case .gentle: return chambersGentle
        case .classic: return chambersClassic
        case .expert: return chambersExpert
        }
    }

    var teamCount: Int { tunnels.reduce(0) { $0 + $1.count } }

    var tileCount: Int {
        var n = 0
        for row in art {
            for s in row.unicodeScalars where s.value >= 97 && s.value < 97 + 24 { n += 1 }
        }
        return n
    }
}

enum Difficulty: String, CaseIterable, Codable, Identifiable {
    case gentle, classic, expert
    var id: String { rawValue }
    var title: String {
        switch self {
        case .gentle: return "Gentle"
        case .classic: return "Classic"
        case .expert: return "Expert"
        }
    }
    var blurb: String {
        switch self {
        case .gentle: return "Extra slots, and each tunnel tells you whether its team can finish now."
        case .classic: return "The intended challenge. Scout, plan, undo freely."
        case .expert: return "Only the slots the designed solution needs — little room to wait."
        }
    }
    var showsFitBadges: Bool { self == .gentle }
    /// Position in (gentle, classic, expert) arrays.
    var index: Int {
        switch self {
        case .gentle: return 0
        case .classic: return 1
        case .expert: return 2
        }
    }
}

/// How hard a mosaic is on one difficulty, from 1 (Relaxed) to 5 (Fiendish).
/// Mirrors `rating()` in Tools/generate_levels.py.
struct PuzzleRating: Equatable {
    let level: Int

    static func from(careless: Double, greedy: Bool) -> PuzzleRating {
        if greedy && careless >= 0.75 { return PuzzleRating(level: 1) }
        if greedy && careless >= 0.35 { return PuzzleRating(level: 2) }
        if greedy { return PuzzleRating(level: 3) }
        if careless > 0.10 { return PuzzleRating(level: 4) }
        return PuzzleRating(level: 5)
    }

    var word: String {
        switch level {
        case 1: return "Relaxed"
        case 2: return "Steady"
        case 3: return "Tricky"
        case 4: return "Hard"
        default: return "Fiendish"
        }
    }

    var explanation: String {
        switch level {
        case 1: return "Almost any order works."
        case 2: return "A little care goes a long way."
        case 3: return "Send teams that can finish now and you'll get there."
        case 4: return "Sending whatever can finish now isn't enough — think a few moves ahead."
        default: return "Needs a real plan: scout, count slots, and use undo."
        }
    }
}

/// Measured difficulty of one mosaic on each difficulty setting.
struct DifficultyStats: Equatable {
    /// Careless (random) win rate on gentle, classic, expert.
    let careless: [Double]
    /// Does the one-step player win on gentle, classic, expert?
    let greedy: [Bool]

    func rating(_ d: Difficulty) -> PuzzleRating {
        PuzzleRating.from(careless: careless[d.index], greedy: greedy[d.index])
    }

    func carelessPercent(_ d: Difficulty) -> Int { Int((careless[d.index] * 100).rounded()) }
}

/// Measures a level on the iPad (pattern and photo levels): careless random play and the
/// one-step greedy player (the same rollout the hints use), on every difficulty.
enum DifficultyProbe {
    static func measure(level: LevelDefinition, trials: Int = 10) -> DifficultyStats {
        let board = Board(art: level.art)
        var careless: [Double] = []
        var greedy: [Bool] = []
        for d in Difficulty.allCases {
            let cap = level.chambers(for: d)
            var rng = SplitMix64(seed: 5)
            var wins = 0
            for _ in 0..<trials {
                let g = Game(level: level, board: board, capacity: cap)
                var steps = 0
                while !g.isWon && steps < 2000 {
                    let fronts = (0..<g.tunnels.count).filter { g.canDispatch($0) }
                    if fronts.isEmpty { break }
                    g.dispatch(fronts[rng.int(fronts.count)])
                    steps += 1
                }
                if g.isWon { wins += 1 }
            }
            careless.append(Double(wins) / Double(max(1, trials)))
            let start = Game(level: level, board: board, capacity: cap)
            greedy.append(HintSolver.rollout(board: board, tunnels: level.tunnels, state: start.state).won)
        }
        return DifficultyStats(careless: careless, greedy: greedy)
    }
}

/// What must be finished before a built-in mosaic opens: any one of `anyOf`.
struct UnlockRule {
    let anyOf: [String]
    /// Shown as "Locked — finish <label>".
    let label: String
}

