    /// Is a seasonal pack in season on `date`? (false for every other pack)
    static func isInSeason(_ packID: String, on date: Date = Date()) -> Bool {
        guard let s = seasons.first(where: { $0.packID == packID }) else { return false }
        let parts = Calendar.current.dateComponents([.month, .day], from: date)
        let md = (parts.month ?? 1) * 100 + (parts.day ?? 1)
        let from = s.from.0 * 100 + s.from.1
        let to = s.to.0 * 100 + s.to.1
        return from <= to ? (md >= from && md <= to) : (md >= from || md <= to)
    }

