    /// The unlock rule for a built-in mosaic (nil = open from the start).
    static func unlockRule(for id: String) -> UnlockRule? {
        if let req = unlockedBy[id] {
            return UnlockRule(anyOf: [req], label: builtIn.first(where: { $0.id == req })?.title ?? req)
        }
        if let p = packOfLevel[id], p != "main" { return packRule(p) }
        return nil
    }

