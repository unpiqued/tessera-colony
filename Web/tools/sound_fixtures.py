"""Writes test/fixtures/sounds.json from the reference sound model (../Tools/sounds.py) for
test/sound.test.js.

  python3 tools/sound_fixtures.py            (run from Web/)

Contents:
  * tables: play-time gains, the action / goal sets, the tile scale, partial recipes, throttle constants
  * noise: the first values of the 64-bit LCG for a few seeds
  * primitives: short strike / glide / swish / lowpass / echo outputs (full arrays)
  * sounds: per sound key the length, peak, RMS, checksum (sum |x|), sum of squares, the first 48 and
    last 8 samples and every 127th sample (float32 values, exact in JSON)
  * worst_case_mix: the loudest plausible moment (sounds.worst_case_mix)
  * pump: the clink timing simulation (sounds.pump_simulation) for every speed plan in
    sounds.SPEED_PLANS on deterministic trip sets: tick times, the clinks heard and the summary stats.
    Trips are generated by a formula the JS test reproduces bit for bit (no RNG); the tick times
    use Python's random module, so they are stored.
"""
import json
import math
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOLS = os.path.normpath(os.path.join(HERE, "..", "..", "Tools"))
sys.path.insert(0, TOOLS)

import numpy as np  # noqa: E402
import sounds as S  # noqa: E402

STRIDE = 127
HEAD = 48
TAIL = 8


def f32list(x):
    return [float(v) for v in np.asarray(x, dtype=np.float32)]


def f64list(x):
    return [float(v) for v in np.asarray(x, dtype=np.float64)]


def sound_entry(x):
    x64 = x.astype(np.float64)
    return {
        "n": int(len(x)),
        "peak": float(np.max(np.abs(x64))),
        "rms": float(np.sqrt(np.mean(x64 ** 2))),
        "checksum": float(np.sum(np.abs(x64))),
        "sumsq": float(np.sum(x64 ** 2)),
        "head": f32list(x[:HEAD]),
        "tail": f32list(x[-TAIL:]),
        "stride": f32list(x[::STRIDE]),
    }


# ---- deterministic trip sets (the JS test rebuilds them with the same arithmetic) ----
PHI = 0.6180339887498949
PLASTIC = 0.7548776662466927


def make_trips(count, span):
    """(arrive, home) game times: a low-discrepancy spread over `span` seconds, homes 0.8-2.5 s later."""
    out = []
    for i in range(count):
        a = span * ((i * PHI) % 1.0)
        h = a + 0.8 + 1.7 * ((i * PLASTIC) % 1.0)
        out.append((a, h))
    return out


TRIP_SETS = {"steady": (1500, 60.0), "slow": (200, 12.0), "long": (3000, 390.0)}
PLAN_TRIPS = {"1x": "steady", "16x": "steady", "0.1x": "slow", "jumps": "long", "drags": "long"}


def ticks_for(trips, plan, seed=5):
    """The real tick times pump_simulation walks through (same RNG calls, same stop condition)."""
    rng = random.Random(seed)
    clock = S.Clock(plan[0][1])
    pending = list(plan[1:])
    end_game = max(h for _, h in trips) + 1.0
    r = 0.0
    out = []
    while clock.game(r) < end_game:
        while pending and pending[0][0] <= r:
            rc, v = pending.pop(0)
            clock.set_speed(v, rc)
        out.append(r)
        r += S.TICK * (1 + 0.2 * (rng.random() - 0.5))
    return out


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "test", "fixtures", "sounds.json")
    sounds = S.build_all()
    fx = {"_about": "Generated by Web/tools/sound_fixtures.py from Tools/sounds.py; do not edit."}
    fx["tables"] = {
        "rate": S.RATE,
        "gains": S.GAINS,
        "action": S.ACTION_SET,
        "goal": S.GOAL_SET,
        "tileScale": S.TILE_SCALE,
        "glass": S.GLASS, "marimba": S.MARIMBA, "bell": S.BELL, "wood": S.WOOD,
        "marimbaShort": S.MARIMBA_SHORT, "glassBell": S.GLASS_BELL,
        "tileGap": S.TILE_GAP, "deliverGap": S.DELIVER_GAP, "voices": S.VOICES,
        "tileLen": S.TILE_LEN, "deliverLen": S.DELIVER_LEN,
        "tick": S.TICK, "lookahead": S.LOOKAHEAD, "stale": S.STALE,
        "keys": list(sounds.keys()),
    }
    fx["noise"] = {str(seed): f64list(S.Noise(seed).block(64)) for seed in (1, 11, 62, 120, 2 ** 63 + 12345)}
    fx["primitives"] = {
        "strike_glass_click": f64list(S.strike(659.26, S.GLASS, 0.02, click=0.18, seed=17)),
        "strike_thud": f64list(S.strike(140.0, [(1.0, 1.0, 0.05), (2.0, 0.2, 0.03)], 0.02, click=0.3, click_decay=0.004, seed=71)),
        "glide": f64list(S.glide(520.0, 260.0, 0.012, 0.08, 0.03, harmonic2=0.25)),
        "swish": f64list(S.swish(0.02, 1500.0, 0.005, 0.006, 62)),
        "swish_reverse": f64list(S.swish(0.02, 3000.0, 0.012, 0.05, 81, reverse=True)),
        "highpass": f64list(S.highpass(S.Noise(3).block(600), 2000.0)),
        "echo_place": f64list(S.echo(S.place(0.01, [(0.0, S.strike(880.0, S.WOOD, 0.006), 0.7),
                                                    (0.002, S.strike(990.0, S.WOOD, 0.006), 0.5)]), 0.003, 0.3, 2)),
    }
    fx["sounds"] = {k: sound_entry(x) for k, x in sounds.items()}
    fx["checksums"] = S.checksums(sounds)
    fx["worst_case_mix"] = S.worst_case_mix(sounds)
    fx["tripSets"] = {k: {"count": c, "span": s} for k, (c, s) in TRIP_SETS.items()}
    fx["tripConstants"] = {"phi": PHI, "plastic": PLASTIC}
    pump = {}
    for name, plan in S.SPEED_PLANS.items():
        set_name = PLAN_TRIPS[name]
        trips = make_trips(*TRIP_SETS[set_name])
        heard = S.pump_simulation(trips, plan, return_heard=True)
        stats = S.pump_simulation(trips, plan)
        pump[name] = {
            "trips": set_name,
            "plan": [[float(r), float(v)] for r, v in plan],
            "ticks": ticks_for(trips, plan),
            "heardKinds": "".join("t" if k == "tile" else "d" for k, _, _ in heard),
            "heardStarts": [float(st) for _, _, st in heard],
            "stats": stats,
        }
        print(name, stats, file=sys.stderr)
    fx["pump"] = pump
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(fx, f, separators=(",", ":"))
    print("wrote", out_path, os.path.getsize(out_path) // 1024, "KB", file=sys.stderr)


if __name__ == "__main__":
    main()
